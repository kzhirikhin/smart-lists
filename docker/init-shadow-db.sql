-- Shadow-база для `prisma migrate dev`.
--
-- Зачем: Prisma накатывает на пустую базу всю историю миграций, чтобы отличить
-- дрейф от намеренного изменения схемы и вычислить SQL новой миграции. По
-- умолчанию она создаёт такую базу сама, но для этого нужен `CREATEDB`, а
-- локальный `DIRECT_URL` намеренно работает под ролью без этого права.
--
-- Почему здесь: скрипты из `/docker-entrypoint-initdb.d/` выполняются при
-- инициализации пустого каталога данных, а данные контейнера живут в tmpfs.
-- Значит база создаётся заново при каждом `up` и не может «протухнуть».
--
-- Содержимого у неё нет по определению: Prisma стирает её перед каждым
-- использованием, пользовательские данные сюда не попадают.
CREATE DATABASE smartlists_shadow;
